-- Брендтік пакет атауы аударылмайды (Патша, 2026-11-25): 0035-те сынақ ұсыныстарына қосылған орысша аудармалар алынады.
-- Тек сынақ мекемелері және тек сол аудармалар — мекеменің өз жазбасы өзгермейді.
UPDATE "app"."offers" o SET details = o.details - 'packNameRu'
FROM "app"."venues" v
WHERE v.id = o.venue_id
  AND v.slug IN ('damdi', 'kebab', 'bahandi', 'dodo', 'coffee-lab', 'tan', 'qala-coffee', 'qala-barber')
  AND o.details->>'packNameRu' IN ('Сытный', 'Дуэт', 'Чабан', 'Большой аппетит', 'Бургер-марафон', 'Сырный вечер', 'Утренний заряд', 'Пенный день', 'Чёрное золото', 'Аккуратный', 'Мужской стиль');
