-- Сынақ ұсыныстарына пакет атауы (Патша, 2026-11-25): «Тойымды» сияқты атау карточкада басты орында, астында тауар атауы.
-- Тек сынақ (seed) мекемелерінің ұсыныстары, тек атауы әлі қойылмағандары — мекеме өзі қойған атау өзгермейді.
-- Санат пен іздеу сөздері де толады (іздеу 2-кезеңін көруге).
WITH n(slug, pn, pn_ru, cat, kw) AS (VALUES
  ('doner', 'Тойымды', 'Сытный', 'Дөнер', '["шаурма", "лаваш"]'),
  ('doner-drink', 'Екеуі бірге', 'Дуэт', 'Комбо', '["донер", "сусын"]'),
  ('lamb-doner', 'Шопан', 'Чабан', 'Дөнер', '["қой еті", "баранина"]'),
  ('burger-combo', 'Үлкен аппетит', 'Большой аппетит', 'Комбо', '["фри", "картошка"]'),
  ('burger', 'Бургер-марафон', 'Бургер-марафон', 'Бургер', '["чизбургер"]'),
  ('pizza', 'Сырлы кеш', 'Сырный вечер', 'Пицца', '["маргарита", "ірімшік"]'),
  ('latte', 'Таңғы серпін', 'Утренний заряд', 'Кофе', '["латте", "сүт"]'),
  ('cappuccino', 'Көбікті күн', 'Пенный день', 'Кофе', '["капучино"]'),
  ('americano', 'Қара алтын', 'Чёрное золото', 'Кофе', '["американо", "эспрессо"]'),
  ('haircut', 'Ұқыпты', 'Аккуратный', 'Ерлер шаш қию', '["барбер", "стрижка"]'),
  ('mens-cut', 'Жігіт сәні', 'Мужской стиль', 'Ерлер шаш қию', '["барбер", "fade"]')
)
UPDATE "app"."offers" o
SET details = coalesce(o.details, '{}'::jsonb) || jsonb_build_object('packName', n.pn, 'packNameRu', n.pn_ru, 'keywords', n.kw::jsonb),
    category = coalesce(nullif(o.category, ''), n.cat)
FROM n, "app"."venues" v
WHERE o.slug = n.slug AND v.id = o.venue_id
  AND v.slug IN ('damdi', 'kebab', 'bahandi', 'dodo', 'coffee-lab', 'tan', 'qala-coffee', 'qala-barber')
  AND coalesce(o.details->>'packName', '') = '';
